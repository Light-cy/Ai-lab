# we just keep swapping neighbors that are out of order until everything's sorted.

# Starting with: P, Y, T, H, O, N

# First:
# P and Y are good (P comes before Y)
# Y and T - T should come before Y, swap them: P, T, Y, H, O, N
# Y and H - H comes first, swap: P, T, H, Y, O, N
# Y and O - O comes first, swap: P, T, H, O, Y, N
# Y and N - N comes first, swap: P, T, H, O, N, Y

# Second pass:
# P and T are fine
# T and H - H comes first, swap: P, H, T, O, N, Y
# T and O - O comes first, swap: P, H, O, T, N, Y
# T and N - N comes first, swap: P, H, O, N, T, Y
# T and Y are fine

# Third pass:
# P and H - H comes first, swap: H, P, O, N, T, Y
# P and O - O comes first, swap: H, O, P, N, T, Y
# P and N - N comes first, swap: H, O, N, P, T, Y
# Rest is ok

# Fourth pass:
# H and O are fine
# O and N - N comes first, swap: H, N, O, P, T, Y
# Final list: H, N, O, P, T, Y

# Selection Sort
# find the smallest thing and put it up front, then repeat.

# Start: P, Y, T, H, O, N

# Look for smallest
# Swap P and H: H, Y, T, P, O, N

# Now from position 1: smallest is N (last position)
# Swap Y and N: H, N, T, P, O, Y

# From position 2: smallest is O (4th position)
# Swap T and O: H, N, O, P, T, Y

# From position 3: P is already smallest
# From position 4: T is smallest
# H, N, O, P, T, Y

# Insertion Sort
# builds the sorted list one item at a time

# Start with just P: [P]
# Add Y: Y > P, so [P, Y]
# Add T: T < Y but T > P, so [P, T, Y]
# Add H: H < Y, H < T, H > P -> [P, H, T, Y]
# Add O: O < Y, O < T, O > H -> [P, H, O, T, Y]
# Add N: N < Y, N < T, N < O, N > H -> [P, H, N, O, T, Y]
# final: H, N, O, P, T, Y

# Merge Sort
# splits everything up then merges it back together sorted.

# Split: [P,Y,T] and [H,O,N]
# Split left: [P] and [Y,T] -> [Y] and [T]
# Split right: [H] and [O,N] -> [O] and [N]

# Now merge back:
# Merge Y and T -> T,Y
# Merge P with T,Y -> P,T,Y

# Merge O and N -> N,O
# Merge H with N,O -> H,N,O

# Final merge: P,T,Y with H,N,O
# Compare P and H -> take H
# Compare P and N -> take N
# Compare P and O -> take O
# Now just add P,T,Y
# Final: H,N,O,P,T,Y

def calculate_stats(numbers):
    # sum
    total = sum(numbers)

    # mean
    mean = total / len(numbers)

    # median
    sorted_nums = sorted(numbers)
    n = len(sorted_nums)

    if n % 2 == 1:
        median = sorted_nums[n // 2]
    else:
        mid1 = sorted_nums[n // 2 - 1]
        mid2 = sorted_nums[n // 2]
        median = (mid1 + mid2) / 2

    # mode
    freq = {}
    for num in numbers:
        if num in freq:
            freq[num] += 1
        else:
            freq[num] = 1

    max_count = max(freq.values())
    mode = [num for num, count in freq.items() if count == max_count]

    if len(mode) == len(numbers):
        mode = "No mode"
    elif len(mode) == 1:
        mode = mode[0]

    print("Numbers:", numbers)
    print("Sum:", total)
    print("Mean:", mean)
    print("Median:", median)
    print("Mode:", mode)

numbers = [5, 2, 8, 2, 5, 1, 9]
calculate_stats(numbers)

def dups(lst):
    seen = []
    duplicates = []

    for item in lst:
        if item in seen and item not in duplicates:
            duplicates.append(item)
        seen.append(item)

    return duplicates


