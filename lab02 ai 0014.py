def selection_sort(items):
    """Sorts a list of items into ascending order using the selection sort algorithm."""
    for step in range(len(items)):
        location_of_smallest = step
        for location in range(step, len(items)):
            if items[location] < items[location_of_smallest]:
                location_of_smallest = location

        items[step], items[location_of_smallest] = items[location_of_smallest], items[step]

def merge(left, right):

    result = []
    i = j = 0

    while i < len(left) and j < len(right):
        if left[i] <= right[j]:
            result.append(left[i])
            i += 1
        else:
            result.append(right[j])
            j += 1

    while i < len(left):
        result.append(left[i])
        i += 1

    while j < len(right):
        result.append(right[j])
        j += 1

    return result


def merge_sort(arr):
    if len(arr) <= 1:
        return arr

    queue = [[x] for x in arr]

    while len(queue) > 1:
        left = queue.pop(0)
        right = queue.pop(0)

        merged = merge(left, right)
        queue.append(merged)

    return queue[0] if queue else []



