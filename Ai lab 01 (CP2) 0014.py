def calculator_two(a, b, op='addition', data_type='float'):
    if op == 'addition':
        result = a + b
    elif op == 'subtraction':
        result = a - b
    elif op == 'multiplication':
        result = a * b
    elif op == 'division':
        result = a / b

    if data_type == 'integer':
        return round(result)
    else:
        return result

