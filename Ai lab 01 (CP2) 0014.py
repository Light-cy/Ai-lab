class findTriplets:
  def find_trip(numbers):

    for i in range(len(numbers)):
      for j in range(len(numbers)):
        for k in range(len(numbers)):
          if i != j and i != k and numbers[i]+numbers[j]+numbers[k]==0:
            return [numbers[i],numbers[j],numbers[k]]


