def A_star(start, goal, graph, heuristic):
    cost = 0
    path = [start]
    visited = []
    queue = [cost, path]

    while queue:
        index = 0
        minIndex = 0

        while index < len(queue):
            current_g = queue[minIndex]
            current_path = queue[minIndex + 1]
            current_last_node = current_path[-1]
            current_f = current_g + heuristic[current_last_node]

            compare_g = queue[index]
            compare_path = queue[index + 1]
