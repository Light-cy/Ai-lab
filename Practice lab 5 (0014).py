def GBFS(start, goal, graph, heuristic):
    cost = 0
    path = [start]
    visited = []
    queue = [cost, path]

    while queue:
        index = 0
        minIndex = 0

        while index < len(queue):
            current_path = queue[minIndex + 1]
            current_node = current_path[-1]
            current_heuristic = heuristic[current_node]

            compare_path = queue[index + 1]
            compare_node = compare_path[-1]
            compare_heuristic = heuristic[compare_node]

            if current_heuristic > compare_heuristic:
                minIndex = index
            index = index + 2

        cost = queue.pop(minIndex)
        path = queue.pop(minIndex)
        last = path[-1]

        if last not in visited:
            visited.append(last)

        if last == goal:
            return path, cost

        for child in graph[last].keys():
            if child not in visited:
                NewPath = list(path)
                NewPath.append(child)
                queue.append(cost + graph[last][child])
