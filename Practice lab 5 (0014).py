def BFS_find_all_path(start, end):
    """Find all possible paths from start to end using BFS approach"""
    if start == end:
        return [[start]]

    all_paths = []
    queue = []
    queue.append([start])

    while queue:
        current_path = queue.pop(0)
        current_node = current_path[-1]

        if current_node == end:
            all_paths.append(current_path)
            continue

        for neighbor in graph_one[current_node]:
            if neighbor not in current_path:
                new_path = current_path + [neighbor]
                queue.append(new_path)

    return all_paths


